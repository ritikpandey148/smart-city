  getLang() {
    const lang = localStorage.getItem('sc_lang');
    return this.SUPPORTED.includes(lang) ? lang : this.DEFAULT;
  },

  setLang(lang) {
    if (!this.SUPPORTED.includes(lang)) return;
    localStorage.setItem('sc_lang', lang);
    this.apply();
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  },

  t(key) {
    const lang = this.getLang();
    return (this.translations[lang] && this.translations[lang][key])
        || (this.translations[this.DEFAULT][key])
        || key;
  },

  apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });
    document.documentElement.setAttribute('lang', this.getLang());
    if (window.lucide) lucide.createIcons();
  }
